// Primitive 
/* 7 Primitive Data Types in JavaScript:
1. String: Represents textual data, enclosed in single quotes (' '), double quotes (" "), or backticks (` `).
2. Number: Represents both integer and floating-point numbers.
3. BigInt: Represents integers with arbitrary precision, allowing for very large numbers.
4. Boolean: Represents a logical entity that can have two values: true or false.
5. Undefined: Represents a variable that has been declared but has not been assigned a value.
6. Null: Represents the intentional absence of any object value.
7. Symbol: Represents a unique identifier, often used as keys in objects to avoid name collisions.
*/


// Non-Primitive(Refrence) Data Types in JavaScript:
/* 3 Non-Primitive (Reference) Data Types in JavaScript:
1. Object: Represents a collection of properties, where each property is a key-value pair. Objects can contain various data types, including other objects.
2. Array: A special type of object that represents an ordered list of values. Arrays can hold multiple values of different data types and are accessed using indices.
3. Function: A block of reusable code that performs a specific task. Functions can be defined using function declarations or function expressions and can be invoked to execute the code they contain.
*/